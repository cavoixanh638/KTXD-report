/**
 * Renders an inline vector SVG icon with zero external network dependencies.
 */
export function uiIcon(
  name: UiIconName,
  size = 15,
  extraClass = ''
): string {
  const pathMarkup = ICON_PATHS[name] || '';
  const cls = extraClass ? `ui-svg-icon ${extraClass}` : 'ui-svg-icon';
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${pathMarkup}</svg>`;
}
